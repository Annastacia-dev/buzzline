/** One square path per colour, with runs of the same colour joined so no seams show. */
function draw(rows: string[]): { box: [number, number, number, number]; art: ReactNode } {
  const paths: Record<string, string> = {};
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/([A-Z])\1*/g)) paths[m[1]] = `${paths[m[1]] ?? ''}M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return {
    box: [0, 0, Math.max(...rows.map(r => r.length)), rows.length],
    art: <g shapeRendering="crispEdges">{Object.entries(paths).map(([c, d]) => <path key={c} d={d} fill={PALETTE[c]} />)}</g>,
  };
}

export const PIXELS = Object.fromEntries(Object.entries(GRIDS).map(([k, rows]) => [k, draw(rows)])) as Record<DoodleName, ReturnType<typeof draw>>;
